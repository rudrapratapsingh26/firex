/**
 * Generates firmware/test/ledger_golden.h from the committed valid-chain vector,
 * so the node's C ledger is tested against bytes produced by this reference
 * implementation: payload CBOR, preimage hash, signature and device key.
 *
 *   npm run golden:c
 *
 * Deterministic: it reads ledger/vectors/01-valid-chain.json and never
 * generates keys, so CI can regenerate it and require no diff.
 */
import { createPublicKey } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { encode } from './cbor.ts';
import { entryFromJson, type EntryJson } from './entry.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const VECTOR = join(HERE, '..', 'vectors', '01-valid-chain.json');
const OUT = join(HERE, '..', '..', 'firmware', 'test', 'ledger_golden.h');

const TS_SRC: Record<string, number> = { ntp: 0, rtc: 1, uncertain: 2 };

/** JSON with object keys in canonical CBOR order (shorter first, then bytewise), as the C encoder emits them. */
function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value !== null && typeof value === 'object') {
    const keys = Object.keys(value as Record<string, unknown>).sort((a, b) => {
      const la = Buffer.byteLength(a), lb = Buffer.byteLength(b);
      return la !== lb ? la - lb : Buffer.compare(Buffer.from(a), Buffer.from(b));
    });
    return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalJson((value as Record<string, unknown>)[k])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

function bytes(data: Uint8Array): string {
  const parts = Array.from(data, (b) => `0x${b.toString(16).padStart(2, '0')}`);
  const lines: string[] = [];
  for (let i = 0; i < parts.length; i += 12) lines.push('    ' + parts.slice(i, i + 12).join(', '));
  return lines.join(',\n');
}

function main(): void {
  const vector = JSON.parse(readFileSync(VECTOR, 'utf8')) as {
    public_key_pem: string; media: string[]; log: EntryJson[];
  };
  const spki = new Uint8Array(createPublicKey(vector.public_key_pem).export({ type: 'spki', format: 'der' }));
  const point = spki.slice(spki.length - 65);

  const out: string[] = [];
  out.push('/* Generated by ledger/src/golden-c.ts from ledger/vectors/01-valid-chain.json. Do not edit. */');
  out.push('#ifndef LEDGER_GOLDEN_H', '#define LEDGER_GOLDEN_H', '', '#include <stdint.h>', '');
  out.push('typedef struct {', '    uint64_t seq;', '    uint64_t ts;', '    uint8_t ts_src;', '    const char *type;',
    '    const uint8_t *payload;', '    uint16_t payload_len;', '    const char *payload_json;', '    uint8_t device_id[16];',
    '    uint8_t fw_hash[32];', '    uint8_t prev_hash[32];', '    uint8_t hash[32];', '    uint8_t sig[64];', '} golden_entry_t;', '');

  vector.log.forEach((j, i) => {
    const payload = encode(entryFromJson(j).payload);
    out.push(`static const uint8_t GOLDEN_PAYLOAD_${i}[] = {`, bytes(payload), '};');
  });
  out.push('');
  out.push(`static const golden_entry_t GOLDEN_ENTRIES[${vector.log.length}] = {`);
  vector.log.forEach((j, i) => {
    const e = entryFromJson(j);
    out.push('    {');
    out.push(`        ${e.seq}u, ${e.ts}u, ${TS_SRC[e.ts_src]}, ${JSON.stringify(e.type)},`);
    out.push(`        GOLDEN_PAYLOAD_${i}, sizeof(GOLDEN_PAYLOAD_${i}), ${JSON.stringify(canonicalJson(j.payload))},`);
    for (const field of ['device_id', 'fw_hash', 'prev_hash', 'hash', 'sig'] as const) {
      out.push(`        {${Array.from(e[field], (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')}},`);
    }
    out.push('    },');
  });
  out.push('};', '');
  out.push(`#define GOLDEN_COUNT ${vector.log.length}u`, '');
  out.push('static const uint8_t GOLDEN_PUBKEY[65] = {', bytes(point), '};', '');
  out.push(`static const char GOLDEN_PEM[] = ${JSON.stringify(vector.public_key_pem)};`, '');
  vector.media.forEach((hex, i) => {
    out.push(`static const uint8_t GOLDEN_MEDIA_${i}[32] = {`, bytes(Uint8Array.from(Buffer.from(hex, 'hex'))), '};');
  });
  out.push('', '#endif /* LEDGER_GOLDEN_H */', '');

  writeFileSync(OUT, out.join('\n'), 'utf8');
  console.log(`wrote ${OUT}`);
}

main();
