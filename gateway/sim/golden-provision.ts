/**
 * Writes firmware/test/provision_golden.h: pairing-code derivation, the
 * provisioning message and proof, and a reply MAC, all computed by the
 * gateway's own functions, so the node's C implementation is tested against
 * the bytes the gateway will check.
 *
 *   npm run golden:provision
 *
 * Deterministic: fixed inputs, no keys generated.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { normalisePairingCode, pairingCodeFromBytes, provisionMessage, provisionProof, replyMac } from '../server/pairing.ts';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'firmware', 'test', 'provision_golden.h');

const randomBytes = Uint8Array.from([0x00, 0x1f, 0x20, 0x3f, 0x85, 0xaa, 0xd3, 0xee, 0x57, 0x64]);
const code = normalisePairingCode(pairingCodeFromBytes(randomBytes))!;
const ids = {
  device_id: '6d70642010849d0c483ec2af8e76f1ae',
  ledger_pub: '04' + 'a1'.repeat(64),
  tls_pub: '04' + 'b2'.repeat(64),
  nonce: '00112233445566778899aabbccddeeff',
};
const reply = {
  site_id: 'site-001',
  mqtt_host: '192.168.1.10',
  mqtt_port: 8883,
  ca_pem: '-----BEGIN CERTIFICATE-----\nMIIBfake\n-----END CERTIFICATE-----\n',
  cert_pem: '-----BEGIN CERTIFICATE-----\nMIIBdevice\n-----END CERTIFICATE-----\n',
};

const c = (s: string) => JSON.stringify(s);
const lines = [
  '/* Generated by gateway/sim/golden-provision.ts. Do not edit. */',
  '#ifndef PROVISION_GOLDEN_H',
  '#define PROVISION_GOLDEN_H',
  '',
  '#include <stdint.h>',
  '',
  `static const uint8_t GOLDEN_CODE_RANDOM[10] = {${Array.from(randomBytes, (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')}};`,
  `static const char GOLDEN_CODE[] = ${c(code)};`,
  `static const char GOLDEN_DEVICE_ID[] = ${c(ids.device_id)};`,
  `static const char GOLDEN_LEDGER_PUB[] = ${c(ids.ledger_pub)};`,
  `static const char GOLDEN_TLS_PUB[] = ${c(ids.tls_pub)};`,
  `static const char GOLDEN_NONCE[] = ${c(ids.nonce)};`,
  `static const char GOLDEN_MESSAGE[] = ${c(provisionMessage(ids).toString('utf8'))};`,
  `static const char GOLDEN_PROOF[] = ${c(provisionProof(code, ids))};`,
  `static const char GOLDEN_SITE_ID[] = ${c(reply.site_id)};`,
  `static const char GOLDEN_MQTT_HOST[] = ${c(reply.mqtt_host)};`,
  `static const uint32_t GOLDEN_MQTT_PORT = ${reply.mqtt_port}u;`,
  `static const char GOLDEN_CA_PEM[] = ${c(reply.ca_pem)};`,
  `static const char GOLDEN_CERT_PEM[] = ${c(reply.cert_pem)};`,
  `static const char GOLDEN_REPLY_MAC[] = ${c(replyMac(code, ids.nonce, reply))};`,
  '',
  '#endif /* PROVISION_GOLDEN_H */',
  '',
];
writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`wrote ${OUT}`);
